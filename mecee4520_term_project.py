class DynamicDataset():
    def __init__(self):
        cols_to_skip = [8]
        rows_to_skip=9
        data_filtered = np.delete(data_ml_normalized, cols_to_skip, axis=1)
        data_filtered = data_filtered[rows_to_skip:]

        self.X = data_filtered[:, :-1].astype(np.float32)  # All except last
        self.Y = data_filtered[:, -1:].astype(np.float32)  # Last column (target)

