def create_session(user_agent: str) -> requests.Session:
    session = requests.Session()
    retries = Retry(
        total=3,
        status_forcelist=(429, 500, 502, 503, 504),
        allowed_methods=("GET",),
        backoff_factor=0.5,
        raise_on_status=False,
        respect_retry_after_header=True,
    )
    adapter = HTTPAdapter(max_retries=retries)
    session.mount("https://", adapter)
    session.headers.update({"User-Agent": user_agent})
    return session


def fetch_json(
    session: requests.Session,
    api_root: str,
    path: str,
    params: Dict[str, object] | None,
    *,
    timeout: float,
    verify: bool,
) -> object:
    url = f"{api_root.rstrip('/')}{path}"
    response = session.get(url, params=params, timeout=timeout, verify=verify)
    response.raise_for_status()
    return response.json()


def fetch_sports_metadata(
    session: requests.Session,
    api_root: str,
    *,
    timeout: float,
    verify: bool,
) -> List[Dict[str, object]]:
    try:
        payload = fetch_json(
            session,
            api_root,
            "/sports",
            params=None,
            timeout=timeout,
            verify=verify,
        )
    except requests.RequestException as exc:
        print(
            f"Warning: unable to fetch sports metadata ({exc}). Continuing without it.",
            file=sys.stderr,
        )
        return []

    if not isinstance(payload, list):
        print(
            "Warning: unexpected response format for /sports endpoint.",
            file=sys.stderr,
        )
        return []
    return payload  # type: ignore[return-value]


def build_tag_to_sport_map(metadata: Iterable[Dict[str, object]]) -> Dict[str, Set[str]]:
    tag_map: Dict[str, Set[str]] = {}
    for entry in metadata:
        sport = str(entry.get("sport", "")).strip()
        tags_raw = entry.get("tags", "")
        if not sport or not isinstance(tags_raw, str):
            continue
        for raw_tag in tags_raw.split(","):
            tag_id = raw_tag.strip()
            if not tag_id:
                continue
            tag_map.setdefault(tag_id, set()).add(sport)
    return tag_map


def fetch_live_events(
    session: requests.Session,
    api_root: str,
    *,
    timeout: float,
    verify: bool,
    page_size: int,
) -> Iterator[Dict[str, object]]:
    offset = 0
    while True:
        params = {"closed": "false", "limit": page_size, "offset": offset}
        try:
            payload = fetch_json(
                session,
                api_root,
                "/events",
                params=params,
                timeout=timeout,
                verify=verify,
            )
        except requests.RequestException as exc:
            print(f"Error fetching events: {exc}", file=sys.stderr)
            break

        if not isinstance(payload, list):
            print("Error: unexpected response format for /events endpoint.", file=sys.stderr)
            break

        events: List[Dict[str, object]] = payload  # type: ignore[assignment]
        if not events:
            break

        for event in events:
            yield event

        if len(events) < page_size:
            break
        offset += page_size


def is_sports_event(event: Dict[str, object]) -> bool:
    tags = event.get("tags")
    if not isinstance(tags, list):
        return False
    for tag in tags:
        if not isinstance(tag, dict):
            continue
        label = tag.get("label")
        if isinstance(label, str) and label.lower() == SPORTS_TAG_LABEL:
            return True
    return False


def event_tag_ids(event: Dict[str, object]) -> Set[str]:
    result: Set[str] = set()
    tags = event.get("tags")
    if not isinstance(tags, list):
        return result
    for tag in tags:
        if not isinstance(tag, dict):
            continue
        tag_id = tag.get("id")
        if isinstance(tag_id, str):
            result.add(tag_id)
    return result


def event_tag_labels(event: Dict[str, object]) -> List[str]:
    labels: Set[str] = set()
    tags = event.get("tags")
    if not isinstance(tags, list):
        return []
    for tag in tags:
        if not isinstance(tag, dict):
            continue
        label = tag.get("label")
        if isinstance(label, str):
            labels.add(label)
    return sorted(labels)


def collect_live_sports_markets(
    events: Iterable[Dict[str, object]],
    tag_to_sport: Dict[str, Set[str]],
) -> List[Dict[str, object]]:
    markets: List[Dict[str, object]] = []

    for event in events:
        if not event.get("active", False) or event.get("closed", False):
            continue
        if not is_sports_event(event):
            continue

        tag_ids = event_tag_ids(event)
        sports = sorted({sport for tag_id in tag_ids for sport in tag_to_sport.get(tag_id, set())})
        labels = event_tag_labels(event)

        event_slug = event.get("slug")
        event_title = event.get("title")

        for market in event.get("markets", []) or []:
            if not isinstance(market, dict):
                continue
            if not market.get("active", False) or market.get("closed", False):
                continue

            markets.append(
                {
                    "event_title": event_title,
                    "event_slug": event_slug,
                    "event_tags": labels,
                    "sports": sports,
                    "market_id": market.get("id"),
                    "market_question": market.get("question"),
                    "market_slug": market.get("slug"),
                    "market_end_date": market.get("endDate"),
                    "market_start_date": market.get("startDate"),
                    "market_liquidity": market.get("liquidity"),
                    "market_volume": market.get("volume"),
                    "last_trade_price": market.get("lastTradePrice"),
                    "best_bid": market.get("bestBid"),
                    "best_ask": market.get("bestAsk"),
                }
            )

    return markets


def get_live_sports_markets(
    api_root: str = DEFAULT_API_ROOT,
    page_size: int = DEFAULT_PAGE_SIZE,
    timeout: float = DEFAULT_TIMEOUT,
    insecure: bool = False,
) -> List[Dict[str, object]]:
    """
    Fetch all live sports markets from the Polymarket Gamma API.

    Example:
        markets = get_live_sports_markets()
    """
    verify = not insecure
    session = create_session(DEFAULT_USER_AGENT)
    try:
        metadata = fetch_sports_metadata(
            session,
            api_root,
            timeout=timeout,
            verify=verify,
        )
        tag_to_sport = build_tag_to_sport_map(metadata)

        live_events = fetch_live_events(
            session,
            api_root,
            timeout=timeout,
            verify=verify,
            page_size=page_size,
        )
        markets = collect_live_sports_markets(live_events, tag_to_sport)
    finally:
        session.close()

    return markets


