class Net(nn.Module):
    def mape_loss(self, predictions, targets):
      return torch.mean(torch.abs((targets - predictions) / (targets + 1e-8))) * 100

    def _initialize_weights(self):
      for m in self.modules():
          if isinstance(m, nn.Linear):
              nn.init.kaiming_normal_(m.weight, mode='fan_in', nonlinearity='relu')
              if m.bias is not None:
                nn.init.constant_(m.bias, 0)
          elif isinstance(m, nn.BatchNorm1d):
              nn.init.constant_(m.weight, 1)
              nn.init.constant_(m.bias, 0)
    def __init__(self, input_dim):
      super(Net, self).__init__()

      # Shallow and wide - only 3 hidden layers
      self.fc1 = nn.Linear(input_dim, 2048)
      self.bn1 = nn.BatchNorm1d(2048)
      self.dropout1 = nn.Dropout(0.4)
      self.fc2 = nn.Linear(2048, 2048)
      self.bn2 = nn.BatchNorm1d(2048)
      self.dropout2 = nn.Dropout(0.4)
      self.fc3 = nn.Linear(2048, 1024)
      self.bn3 = nn.BatchNorm1d(1024)
      self.dropout3 = nn.Dropout(0.3)
      self.fc4 = nn.Linear(1024, 1)

      self._initialize_weights()
      self.learning_rate = .0001 #was .001
      self.optimizer = torch.optim.Adam(self.parameters(), lr=self.learning_rate, weight_decay=1e-5)
      self.scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(self.optimizer, mode='min', factor=0.5, patience=5) #patience was 3
      self.num_epochs = 10
      self.batchsize = 256 #was 128
      self.criterion = nn.MSELoss()
      #self.criterion = self.mape_loss #BCELoss better for probability outputs? CHECK. Maybe use BCEWithLogitsLoss()?
      #self.criterion = sMAPELoss()
      self.shuffle = True
      self.float()

    def forward(self, x):
      x = self.dropout1(F.relu(self.bn1(self.fc1(x))))
      x = self.dropout2(F.relu(self.bn2(self.fc2(x))))
      x = self.dropout3(F.relu(self.bn3(self.fc3(x))))
      x = self.fc4(x)
      return x

    def predict(self, features):
      self.eval()
      features = torch.from_numpy(features).float().to(next(self.parameters()).device)
      return self.forward(features).detach().cpu().numpy()


def train(model,epoch,epochs, device):
    model.train()
    total_loss = 0.0
    count = 0
    for i, Edata in enumerate(train_loader):
      X = Edata['X'].to(device)
      Y = Edata['Y'].to(device)
      predictions = model(X)
      loss = model.criterion(predictions,Y)
      model.optimizer.zero_grad()
      loss.backward()
      torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=5.0)
      total_loss += loss.item()
      model.optimizer.step()
      count += 1
    return total_loss / count if count > 0 else 0

