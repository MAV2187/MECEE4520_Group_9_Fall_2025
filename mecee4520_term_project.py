def build_feature_matrix_for_slugs(
    market_slugs: List[str],
    csv_path: str,
) -> Tuple[pd.DataFrame, List[str]]:
    """
    Reconstructs the feature matrix used by the linear regression model
    for the given market slugs.

    Returns:
        feature_matrix: rows indexed by slug, columns in FEATURE_ORDER
        missing_slugs: slugs not found in the reference CSV
    """
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"Reference dataset not found at {csv_path}")

    features_df, missing_slugs = load_market_feature_rows(market_slugs, csv_path)

    if features_df.empty:
        raise RuntimeError("None of the selected markets were found in the reference dataset.")

    # Make sure required raw columns exist
    for col in ("spread", "first_T-15", "first_T-75", "first_T-735", "first_T-1424", "sportsMarketType"):
        if col not in features_df.columns:
            features_df[col] = np.nan

    # Numeric cleanup for time-series columns
    ts_cols = [c for c in features_df.columns if c.startswith("first_T-") or c.startswith("second_T-")]
    if ts_cols:
        features_df[ts_cols] = features_df[ts_cols].apply(pd.to_numeric, errors="coerce")
    features_df["spread"] = pd.to_numeric(features_df["spread"], errors="coerce")

    # Rebuild features exactly as in the notebook
    features_df["p"] = np.clip(features_df["first_T-15"], 1e-16, 1 - 1e-16)
    features_df["price_change_1hr"] = features_df["first_T-15"] - features_df["first_T-75"]
    features_df["price_change_12hr"] = features_df["first_T-15"] - features_df["first_T-735"]
    features_df["price_change_24hr"] = features_df["first_T-15"] - features_df["first_T-1424"]

    # Rolling 24h volatility from first_T-* grid
    vol_cols = []
    for col in features_df.columns:
        if col.startswith("first_T-"):
            try:
                t_val = int(col.split("first_T-")[1])
            except ValueError:
                continue
            if 15 <= t_val <= 1424:
                vol_cols.append(col)

    if vol_cols:
        features_df["rolling_volatility_24hr"] = features_df[vol_cols].std(axis=1, skipna=True)
    else:
        features_df["rolling_volatility_24hr"] = 0.0

    # Category: totals market or not
    type_series = features_df["sportsMarketType"].fillna("").astype(str).str.lower()
    features_df["type_totals"] = (type_series == "totals").astype(int)

