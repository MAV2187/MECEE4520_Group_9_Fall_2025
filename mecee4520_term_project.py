# \begin{lstlisting}[language=Python, caption={Comparison of Brier, Excess Brier, and Penalized Brier for p = 0.99}]
import numpy as np

# --- Define the three scores ---

def brier_score(p, o):
    """Standard Brier score: squared error between probability and outcome."""
    return (p - o)**2

def excess_brier(p, o):
    """
    Excess Brier score:
    (p - o)^2 - p(1 - p)

    Negative  -> overconfident (possibly correct)
    Positive  -> underconfident or badly wrong
    """
    brier = (p - o)**2
    expected_brier = p * (1 - p)
    return brier - expected_brier

def penalized_brier(p, o, lam=1.0):
    """
    Penalized Brier score:
    (p - o)^2 + λ * penalty(p)

    Here we use penalty(p) = (p - 0.5)^2
    which penalizes extreme probabilities.
    """
    brier = (p - o)**2
    penalty = (p - 0.5)**2
    return brier + lam * penalty


