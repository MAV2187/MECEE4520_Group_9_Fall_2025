    feature_matrix[NUMERIC_FEATURE_NAMES] = scaler.transform(
        feature_matrix[NUMERIC_FEATURE_NAMES]
    )

    # Ensure final column order
    feature_matrix = feature_matrix[FEATURE_ORDER]

    return feature_matrix, missing_slugs

