class Net(nn.Module):
    def __init__(self, input_dim: int) -> None:
        super().__init__()

        self.fc1 = nn.Linear(input_dim, 2048)
        self.bn1 = nn.BatchNorm1d(2048)
        self.dropout1 = nn.Dropout(0.4)

        self.fc2 = nn.Linear(2048, 2048)
        self.bn2 = nn.BatchNorm1d(2048)
        self.dropout2 = nn.Dropout(0.4)

        self.fc3 = nn.Linear(2048, 1024)
        self.bn3 = nn.BatchNorm1d(1024)
        self.dropout3 = nn.Dropout(0.3)

        self.fc4 = nn.Linear(1024, 1)

        self.float()

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = self.dropout1(F.relu(self.bn1(self.fc1(x))))
        x = self.dropout2(F.relu(self.bn2(self.fc2(x))))
        x = self.dropout3(F.relu(self.bn3(self.fc3(x))))
        return self.fc4(x)


def to_float(value: str | None) -> float:
    if value is None:
        return 0.0
    text = str(value).strip()
    if not text or text.lower() in {"nan", "null"}:
        return 0.0
    try:
        return float(text)
    except ValueError:
        try:
            return float(text.replace(",", ""))
        except ValueError:
            return 0.0


def download_model_bytes() -> bytes:
    last_error: Exception | None = None
    for url in (MODEL_URL_MEDIA, MODEL_URL_MEDIA_DOWNLOAD, MODEL_URL_RAW):
        try:
            response = requests.get(url, timeout=120)
            response.raise_for_status()
        except requests.RequestException as exc:
            last_error = exc
            continue

        content = response.content
        if content.startswith(LFS_POINTER_PREFIX):
            pointer_preview = content.decode("utf-8", "replace").splitlines()[:3]
            pointer_text = " | ".join(pointer_preview)
            last_error = RuntimeError(
                f"Retrieved Git LFS pointer from {url}; pointer details: {pointer_text}"
            )
            continue

        return content

    if last_error is not None:
        raise RuntimeError("Unable to download model weights.") from last_error
    raise RuntimeError("Unable to download model weights: empty response")


def load_remote_model() -> tuple[Net, int]:
    print("Downloading neural-network weights...")
    model_bytes = download_model_bytes()
    try:
        state_dict = torch.load(BytesIO(model_bytes), map_location=DEVICE, weights_only=False)
    except TypeError:
        # For older PyTorch versions without weights_only argument
        state_dict = torch.load(BytesIO(model_bytes), map_location=DEVICE)
    input_dim = state_dict["fc1.weight"].shape[1]
    print(f"✓ Model downloaded (input dimension: {input_dim})")

    model = Net(input_dim).to(DEVICE)
    model.load_state_dict(state_dict)
    model.eval()
    print(f"✓ Model loaded on {DEVICE}")
    return model, input_dim


def fetch_market_rows(slugs: list[str]) -> tuple[dict[str, list[str]], list[str], dict[str, list[int]], list[str]]:
    remaining = set(slugs)
    rows: dict[str, list[str]] = {}
    index_map: dict[str, list[int]] = defaultdict(list)
    header: list[str] | None = None

    print(f"Fetching reference rows for {len(slugs)} markets...")
    with requests.get(DATASET_URL, stream=True, timeout=(10, 300)) as response:
        response.raise_for_status()
        line_iter = response.iter_lines(decode_unicode=True)
        reader = csv.reader(line for line in line_iter if line)

        try:
            header = next(reader)
        except StopIteration as exc:
            raise RuntimeError("Reference dataset is empty.") from exc

        for idx, name in enumerate(header):
            index_map[name].append(idx)

        slug_indices = index_map.get("slug")
        if not slug_indices:
            raise RuntimeError("Reference dataset does not contain a 'slug' column.")
        slug_idx = slug_indices[0]
        expected_len = len(header)

        for row in reader:
            if not remaining:
                break

            if len(row) < expected_len:
                if not row:
                    continue
                row = row + [""] * (expected_len - len(row))
            elif len(row) > expected_len:
                row = row[:expected_len]

            slug_value = row[slug_idx].strip()
            if slug_value in remaining:
                rows[slug_value] = row
                remaining.remove(slug_value)

    missing = sorted(remaining)

    if missing and header is not None:
        local_rows = load_rows_from_local_files(missing, header, index_map)
        for slug, row in local_rows.items():
            if slug in remaining:
                rows[slug] = row
                remaining.remove(slug)
        missing = sorted(remaining)

    return rows, missing, index_map, header or []


def load_rows_from_local_files(
    slugs: list[str],
    header: list[str],
    index_map: dict[str, list[int]],
) -> dict[str, list[str]]:
    remaining = set(slugs)
    collected: dict[str, list[str]] = {}

    if not LOCAL_DATASET_DIR.exists():
        return collected

    desired_columns = {"slug"}
    desired_columns.update(name for name, _ in BASE_COLUMN_ORDER)
    desired_columns.update(FIRST_T_COLUMNS)
    desired_columns = desired_columns.intersection(index_map.keys())

    for csv_path in LOCAL_DATASET_FILES:
        if not remaining:
            break
        if not csv_path.exists():
            continue

        try:
            reader = pd.read_csv(
                csv_path,
                chunksize=2000,
                usecols=lambda col: col in desired_columns,
                dtype=str,
                low_memory=False,
            )
        except ValueError:
            reader = pd.read_csv(
                csv_path,
                chunksize=2000,
                dtype=str,
                low_memory=False,
            )
        except Exception:
            continue

        if isinstance(reader, pd.DataFrame):
            chunk_iter = [reader]
        else:
            chunk_iter = reader

        for chunk in chunk_iter:
            if "slug" not in chunk.columns:
                continue
            matches = chunk[chunk["slug"].isin(remaining)]
            if matches.empty:
                continue

            for _, row in matches.iterrows():
                slug = str(row["slug"]).strip()
                if not slug or slug not in remaining:
                    continue
                values = [""] * len(header)
                for col_name, value in row.items():
                    if col_name not in index_map:
                        continue
                    for idx in index_map[col_name]:
                        values[idx] = "" if pd.isna(value) else str(value)
                collected[slug] = values
                remaining.remove(slug)
                if not remaining:
                    break
            if not remaining:
                break

    return collected


def value_at(row: list[str], index_map: dict[str, list[int]], name: str, occurrence: int = 0) -> str:
    indices = index_map.get(name)
    if not indices or occurrence >= len(indices):
        return ""
    idx = indices[occurrence]
    if idx >= len(row):
        return ""
    return row[idx]


def build_feature_matrix(
    slugs: list[str],
    rows: dict[str, list[str]],
    index_map: dict[str, list[int]],
) -> tuple[np.ndarray, list[str]]:
    feature_vectors: list[list[float]] = []
    available_slugs: list[str] = []

    for slug in slugs:
        row = rows.get(slug)
        if row is None:
            continue

        vector: list[float] = []
        for name, occurrence in BASE_COLUMN_ORDER:
            vector.append(to_float(value_at(row, index_map, name, occurrence)))

        for column in FIRST_T_COLUMNS:
            vector.append(to_float(value_at(row, index_map, column)))

        if len(vector) != EXPECTED_FEATURES:
            raise RuntimeError(
                f"Feature vector for slug '{slug}' has {len(vector)} values; expected {EXPECTED_FEATURES}."
            )

        feature_vectors.append(vector)
        available_slugs.append(slug)

    return np.asarray(feature_vectors, dtype=np.float32), available_slugs


