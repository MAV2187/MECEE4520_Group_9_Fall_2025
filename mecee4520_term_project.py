def parse_layer_string(layer_str):
    """
    Parse a layer string like:
    'Linear(in_features=1433, out_features=2048, bias=True)'
    'BatchNorm1d(2048, eps=1e-05, momentum=0.1, affine=True, track_running_stats=True)'

    Returns: (layer_type, params_dict)
    """
    # Extract layer type
    layer_type = layer_str.split('(')[0]

    # Extract parameters
    params_str = layer_str[layer_str.find('(')+1:layer_str.rfind(')')]

    params = {}
    positional_args = []  # ✅ Track positional arguments

    # Split by comma, but handle nested parentheses
    parts = []
    current = []
    paren_depth = 0

    for char in params_str + ',':
        if char == ',' and paren_depth == 0:
            parts.append(''.join(current).strip())
            current = []
        else:
            if char == '(':
                paren_depth += 1
            elif char == ')':
                paren_depth -= 1
            current.append(char)

    for part in parts:
        if not part:  # Skip empty parts
            continue

        if '=' in part:
            # Named parameter
            key, value = part.split('=', 1)
            key = key.strip()
            value = value.strip()

            # Convert value to appropriate type
            if value == 'True':
                params[key] = True
            elif value == 'False':
                params[key] = False
            elif value == 'None':
                params[key] = None
            elif 'e-' in value or 'e+' in value:  # Scientific notation
                params[key] = float(value)
            elif '.' in value:  # Float
                try:
                    params[key] = float(value)
                except:
                    params[key] = value
            else:  # Try int, fallback to string
                try:
                    params[key] = int(value)
                except:
                    params[key] = value
        else:
            # Positional argument
            value = part.strip()
            # Convert to int (most positional args are integers like 2048)
            try:
                positional_args.append(int(value))
            except:
                try:
                    positional_args.append(float(value))
                except:
                    positional_args.append(value)

    # ✅ Add positional arguments to params with standard names
    if layer_type == 'BatchNorm1d' and positional_args:
        params['num_features'] = positional_args[0]
    elif layer_type == 'Linear' and positional_args:
        if len(positional_args) >= 1:
            params['in_features'] = positional_args[0]
        if len(positional_args) >= 2:
            params['out_features'] = positional_args[1]
    elif layer_type == 'Dropout' and positional_args:
        params['p'] = positional_args[0]

    return layer_type, params


def parse_stats_file(stats_path):
    """
    Parse ModelStatistics.txt to extract layer structure

    Returns: dict with 'layers' list and other metadata
    """
    with open(stats_path, 'r') as f:
        lines = f.readlines()

    config = {
        'layers': [],
        'input_dim': None,
        'architecture_name': None
    }

    in_layer_section = False

    for line in lines:
        line = line.strip()

        # Extract architecture name
        if 'Architecture:' in line:
            config['architecture_name'] = line.split('Architecture:')[1].strip()

        # Extract input dimension
        if 'Input Dimension:' in line:
            config['input_dim'] = int(line.split('Input Dimension:')[1].strip())

        # Check if we're in the layer structure section
        if 'LAYER STRUCTURE:' in line:
            in_layer_section = True
            continue

        # Check if we've left the layer structure section
        if in_layer_section and 'CONFIGURATION:' in line:
            in_layer_section = False
            continue

        # Parse layer lines
        if in_layer_section and line and not line.startswith('-'):
            # Skip empty lines and separator lines
            parts = line.split(None, 1)  # Split on first whitespace
            if len(parts) == 2:
                layer_name, layer_def = parts
                if '(' in layer_def:  # Make sure it's a layer definition
                    layer_type, params = parse_layer_string(layer_def)
                    config['layers'].append({
                        'name': layer_name,
                        'type': layer_type,
                        'params': params
                    })

    return config


def build_model_from_stats(stats_path):
    """
    Build a PyTorch model dynamically from ModelStatistics.txt
    """
    config = parse_stats_file(stats_path)

    print(f"Parsed {len(config['layers'])} layers:")
    for layer in config['layers']:
        print(f"  {layer['name']:15} {layer['type']}")

    class DynamicNet(nn.Module):
        def __init__(self, layer_configs):
            super(DynamicNet, self).__init__()

            # Build layers from config
            for layer_cfg in layer_configs:
                name = layer_cfg['name']
                layer_type = layer_cfg['type']
                params = layer_cfg['params']

                # Create the layer
                if layer_type == 'Linear':
                    layer = nn.Linear(
                        in_features=params['in_features'],
                        out_features=params['out_features'],
                        bias=params.get('bias', True)
                    )

                elif layer_type == 'BatchNorm1d':
                    layer = nn.BatchNorm1d(
                        num_features=int(params['num_features']),
                        eps=params.get('eps', 1e-05),
                        momentum=params.get('momentum', 0.1),
                        affine=params.get('affine', True),
                        track_running_stats=params.get('track_running_stats', True)
                    )

                elif layer_type == 'Dropout':
                    layer = nn.Dropout(
                        p=params.get('p', 0.5),
                        inplace=params.get('inplace', False)
                    )

                else:
                    raise ValueError(f"Unknown layer type: {layer_type}")

                # Register the layer
                setattr(self, name, layer)

            self.float()

        def forward(self, x):
            """
            Explicit forward pass matching the training architecture
            Pattern: Linear → BatchNorm → ReLU → Dropout (repeat)
            """
            # ✅ Explicitly define the forward pass for shallow & wide architecture
            # This matches the original Net forward() exactly

            # Block 1: fc1 → bn1 → relu → dropout1
            x = self.fc1(x)
            x = self.bn1(x)
            x = F.relu(x)
            x = self.dropout1(x)

            # Block 2: fc2 → bn2 → relu → dropout2
            x = self.fc2(x)
            x = self.bn2(x)
            x = F.relu(x)
            x = self.dropout2(x)

            # Block 3: fc3 → bn3 → relu → dropout3
            x = self.fc3(x)
            x = self.bn3(x)
            x = F.relu(x)
            x = self.dropout3(x)

            # Output: fc4 (no activation)
            x = self.fc4(x)

            return x

    model = DynamicNet(config['layers'])
    return model, config

