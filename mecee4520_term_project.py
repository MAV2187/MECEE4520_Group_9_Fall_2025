def get_model_info(model):
    # Count parameters
    total_params = sum(p.numel() for p in model.parameters())
    trainable_params = sum(p.numel() for p in model.parameters() if p.requires_grad)

    # Get architecture name
    architecture_names = {
        0: "Deep with Dropout",
        1: "Deep with BatchNorm",
        2: "ResNet-style with Skip Connections",
        3: "Bottleneck (Wide→Narrow→Wide)",
        4: "Shallow and Wide",
        5: "Improved Shallow and Wide"
    }

    # Get layer structure
    layers = []
    for name, module in model.named_modules():
        if isinstance(module, (nn.Linear, nn.BatchNorm1d, nn.Dropout)):
            layers.append((name, str(module)))

    return {
        'architecture_name': "Shallow and wide - only 3 hidden layers",
        'total_params': total_params,
        'trainable_params': trainable_params,
        'layers': layers
    }

