def load_market_feature_rows(
    slugs: List[str],
    csv_path: str,
    chunksize: int = 2000,
) -> Tuple[pd.DataFrame, List[str]]:
    """
    Stream through the large CSV and pull rows whose `slug` is in `slugs`.
    Returns:
        features_df: df indexed by slug
        missing_slugs: slugs that were not found
    """
    remaining = set(slugs)
    collected = []

    for chunk in pd.read_csv(csv_path, chunksize=chunksize):
        matches = chunk[chunk["slug"].isin(remaining)]
        if not matches.empty:
            collected.append(matches)
            remaining -= set(matches["slug"])
            if not remaining:
                break

    if collected:
        frame = (
            pd.concat(collected, ignore_index=True)
            .drop_duplicates(subset="slug", keep="first")
            .set_index("slug")
        )
    else:
        frame = pd.DataFrame()

    return frame, sorted(remaining)

